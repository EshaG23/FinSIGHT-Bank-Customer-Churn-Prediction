# Read the EDA split; we will not split the full dataset again.
X_train_raw = pd.read_csv(output_folder / 'X_train_encoded.csv')
X_train_scaled = pd.read_csv(output_folder / 'X_train_scaled.csv')
X_test_scaled = pd.read_csv(output_folder / 'X_test_scaled.csv')
y_train = pd.read_csv(output_folder / 'y_train.csv')['Exited']
y_test = pd.read_csv(output_folder / 'y_test.csv')['Exited']
scale_columns = joblib.load(output_folder / 'scale_columns.pkl')
print('Training:', X_train_raw.shape, 'Testing:', X_test_scaled.shape)
print('Training churn distribution (%):')
print((y_train.value_counts(normalize=True) * 100).round(2))


# ==================================================================
# KNN classifier from scratch
# ==================================================================
# Our KNN stores training customers, then finds the nearest ones.
class KNN:
    def __init__(self, k=3, voting='uniform'):
        self.k = k
        self.voting = voting

    def fit(self, X, y):
        self.X_train = np.asarray(X, dtype=float)
        self.y_train = np.asarray(y, dtype=int)

    def euclidean_distance(self, x1, x2):
        return np.sqrt(np.sum((x1 - x2) ** 2))

    def nearest(self, x, max_k=None):
        # Same Euclidean formula as ma'am; NumPy calculates all distances faster.
        distances = np.sqrt(np.sum((self.X_train - x) ** 2, axis=1))
        k = self.k if max_k is None else max_k
        indices = np.argsort(distances)[:k]
        return self.y_train[indices], distances[indices]

    def score_neighbours(self, labels, distances, k, voting):
        labels, distances = labels[:k], distances[:k]
        if voting == 'uniform':
            return float(np.mean(labels))
        # Closer neighbours get more weight; avoid division by zero.
        if np.any(distances == 0):
            return float(np.mean(labels[distances == 0]))
        weights = 1 / (distances + 1e-8)
        return float(np.sum(weights * labels) / np.sum(weights))

    def predict_proba_single(self, x):
        labels, distances = self.nearest(x)
        return self.score_neighbours(labels, distances, self.k, self.voting)

    def predict_single(self, x):
        score = self.predict_proba_single(x)
        return int(score >= 0.5)

    def predict_proba(self, X):
        return np.array([self.predict_proba_single(x) for x in X])

    def predict(self, X):
        return np.array([self.predict_single(x) for x in X])


# ==================================================================
# Validation subset for tuning
# ==================================================================
# Split the existing training set for experiments only.
X_sub_raw, X_val_raw, y_sub, y_val = train_test_split(
    X_train_raw, y_train, test_size=0.20, random_state=42, stratify=y_train
)

# Take smaller stratified samples so from-scratch KNN runs faster in Colab.
sub_ids, _ = train_test_split(np.arange(len(y_sub)), train_size=2000,
                              random_state=42, stratify=y_sub)
val_ids, _ = train_test_split(np.arange(len(y_val)), train_size=400,
                              random_state=42, stratify=y_val)
X_sub = X_sub_raw.iloc[sub_ids].reset_index(drop=True)
y_sub_small = y_sub.iloc[sub_ids].reset_index(drop=True)
X_val = X_val_raw.iloc[val_ids].reset_index(drop=True)
y_val_small = y_val.iloc[val_ids].reset_index(drop=True)
print('Tuning train:', len(y_sub_small), '| Validation:', len(y_val_small))


# ==================================================================
# Six improvement experiments
# ==================================================================
# Our experiment settings (easy to understand and modify).
k_values = [1, 3, 5, 7, 9, 11, 15, 19, 25, 31]
voting_methods = ['uniform', 'distance']
thresholds = [0.30, 0.35, 0.40, 0.45, 0.50, 0.55]
scaling_methods = ['standard', 'minmax']
balance_methods = ['original', 'undersampled']
feature_sets = {
    'all': X_train_raw.columns.tolist(),
    'selected': ['CreditScore', 'Age', 'Balance', 'NumOfProducts',
                 'IsActiveMember', 'Geography_France', 'Geography_Germany',
                 'Geography_Spain', 'Gender_Female', 'Gender_Male']
}

# Fit the scaler only on the experiment training customers.
def prepare_features(train_data, val_data, method, columns):
    a, b = train_data[columns].copy(), val_data[columns].copy()
    numeric = [col for col in scale_columns if col in columns]
    scaler = StandardScaler() if method == 'standard' else MinMaxScaler()
    a[numeric] = scaler.fit_transform(a[numeric])
    b[numeric] = scaler.transform(b[numeric])
    return a.to_numpy(dtype=float), b.to_numpy(dtype=float)

# Keep all churn customers, and randomly select equally many non-churn customers.
def balance_training(X, y, method):
    y = np.asarray(y)
    if method == 'original':
        return X, y
    rng = np.random.default_rng(42)
    churn = np.where(y == 1)[0]
    stayed = np.where(y == 0)[0]
    selected_stayed = rng.choice(stayed, size=len(churn), replace=False)
    selected = np.concatenate([churn, selected_stayed])
    rng.shuffle(selected)
    return X[selected], y[selected]

# We use F1 to choose the model, while also watching churn recall.
results = []
all_experiments = len(scaling_methods) * len(balance_methods) * len(feature_sets)
print('Running', all_experiments, 'feature/scaling/balance combinations...')
for scaling in scaling_methods:
    for balancing in balance_methods:
        for features_name, columns in feature_sets.items():
            a, b = prepare_features(X_sub, X_val, scaling, columns)
            a, labels = balance_training(a, y_sub_small, balancing)
            model = KNN(k=max(k_values))
            model.fit(a, labels)
            # Neighbours are computed only once for each validation customer.
            neighbours = [model.nearest(row, max(k_values)) for row in b]
            for k in k_values:
                for voting in voting_methods:
                    scores = np.array([model.score_neighbours(lab, dist, k, voting)
                                       for lab, dist in neighbours])
                    for threshold in thresholds:
                        predicted = (scores >= threshold).astype(int)
                        results.append({
                            'Scaling': scaling, 'Balance': balancing,
                            'Features': features_name, 'K': k,
                            'Voting': voting, 'Threshold': threshold,
                            'Accuracy': accuracy_score(y_val_small, predicted),
                            'Precision': precision_score(y_val_small, predicted, zero_division=0),
                            'Recall': recall_score(y_val_small, predicted, zero_division=0),
                            'F1': f1_score(y_val_small, predicted, zero_division=0)
                        })
    print('Finished scaling:', scaling)

results_df = pd.DataFrame(results)
results_df = results_df.sort_values(['F1', 'Recall', 'Precision'], ascending=False).reset_index(drop=True)
print('Best 10 validation experiments:')
print(results_df.head(10).round(4).to_string(index=False))


# ==================================================================
# Best validation settings and charts
# ==================================================================
# Show the winning configuration, selected only from validation results.
best = results_df.iloc[0]
print('BEST VALIDATION CONFIGURATION:')
for col in ['K', 'Voting', 'Threshold', 'Scaling', 'Balance', 'Features',
            'Accuracy', 'Precision', 'Recall', 'F1']:
    print(col + ':', best[col])

# Compare the six improvement choices using their highest validation F1.
fig, axes = plt.subplots(2, 3, figsize=(14, 8))
for ax, col in zip(axes.flat, ['K', 'Voting', 'Threshold', 'Scaling', 'Balance', 'Features']):
    values = results_df.groupby(col)['F1'].max()
    ax.bar(values.index.astype(str), values.values)
    ax.set_title('Best validation F1 by ' + col)
    ax.set_ylim(0, 1)
    ax.tick_params(axis='x', rotation=30)
plt.tight_layout()
plt.show()


# ==================================================================
# Final evaluation on untouched testing data
# ==================================================================
# Refit preprocessing using all training customers; transform testing customers.
# The encoded test CSV contains the same unscaled columns as training.
X_test_raw_path = output_folder / 'X_test_encoded.csv'
if not X_test_raw_path.exists():
    raise FileNotFoundError('Upload X_test_encoded.csv from your EDA outputs as the seventh file.')
X_test_raw = pd.read_csv(X_test_raw_path)

chosen_features = feature_sets[str(best['Features'])]
X_full, X_final_test = prepare_features(X_train_raw, X_test_raw,
                                       str(best['Scaling']), chosen_features)
X_full, y_full = balance_training(X_full, y_train, str(best['Balance']))
final_knn = KNN(k=int(best['K']), voting=str(best['Voting']))
final_knn.fit(X_full, y_full)
print('Calculating neighbours for all', len(X_final_test), 'test customers...')
final_scores = final_knn.predict_proba(X_final_test)
final_pred = (final_scores >= float(best['Threshold'])).astype(int)
final_auc = roc_auc_score(y_test, final_scores)
final_metrics = {
    'Accuracy': accuracy_score(y_test, final_pred),
    'Precision': precision_score(y_test, final_pred, zero_division=0),
    'Recall': recall_score(y_test, final_pred, zero_division=0),
    'F1': f1_score(y_test, final_pred, zero_division=0),
    'ROC-AUC': final_auc
}
print('FINAL TEST RESULTS:')
print(pd.Series(final_metrics).round(4))
print('\nClassification report:')
print(classification_report(y_test, final_pred, zero_division=0))
cm = confusion_matrix(y_test, final_pred)
print('Confusion matrix:\n', cm)


