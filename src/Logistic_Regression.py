# FinSIGHT — Logistic Regression From Scratch


# 1. Import libraries and locate EDA outputs


# We use simple NumPy calculations and the same evaluation commands as our practicals.
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
import joblib
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from sklearn.metrics import classification_report, confusion_matrix, roc_auc_score, roc_curve

# Locate our EDA files in the existing VS Code project.
PROJECT_FOLDER = Path(__file__).resolve().parent.parent
output_folder = PROJECT_FOLDER / 'outputs'
required = ['X_train_encoded.csv', 'X_test_encoded.csv', 'y_train.csv', 'y_test.csv']
missing = [name for name in required if not (output_folder / name).exists()]
if missing:
    raise FileNotFoundError('Run FULL_EDA.py first. Missing: ' + ', '.join(missing))
print('Reading data from:', output_folder)


# 2. Load data and check shapes


# These files were generated by FULL_EDA. All models must use the same test customers.
X_train_df = pd.read_csv(output_folder / 'X_train_encoded.csv')
X_test_df = pd.read_csv(output_folder / 'X_test_encoded.csv')
y_train = pd.read_csv(output_folder / 'y_train.csv')['Exited'].to_numpy(dtype=int)
y_test = pd.read_csv(output_folder / 'y_test.csv')['Exited'].to_numpy(dtype=int)

# Keep feature names and order exactly the same in both files.
X_test_df = X_test_df[X_train_df.columns]
print('Train:', X_train_df.shape, '| Test:', X_test_df.shape)
print('Number of churners in test data:', y_test.sum())
print('Features:', X_train_df.columns.tolist())


# 3. Logistic Regression algorithm (from scratch)


# Make Logistic Regression using only NumPy, similar to ma'am's from-scratch classes.
class LogisticRegressionScratch:
    def __init__(self, learning_rate=0.1, epochs=1200, l2=0.0, balanced=False):
        self.learning_rate = learning_rate
        self.epochs = epochs
        self.l2 = l2
        self.balanced = balanced

    def sigmoid(self, z):
        z = np.clip(z, -500, 500)  # Avoid numerical overflow.
        return 1 / (1 + np.exp(-z))

    def fit(self, X, y):
        X = np.asarray(X, dtype=float)
        y = np.asarray(y, dtype=float)
        rows, cols = X.shape
        self.weights = np.zeros(cols)
        self.bias = 0.0

        # Optional class weights give additional importance to actual churners.
        if self.balanced:
            positive = max(1, np.sum(y == 1))
            negative = max(1, np.sum(y == 0))
            sample_weights = np.where(y == 1, rows / (2 * positive), rows / (2 * negative))
        else:
            sample_weights = np.ones(rows)

        for epoch in range(self.epochs):
            linear = np.dot(X, self.weights) + self.bias
            predictions = self.sigmoid(linear)
            errors = (predictions - y) * sample_weights
            dw = np.dot(X.T, errors) / rows + self.l2 * self.weights
            db = np.sum(errors) / rows
            self.weights -= self.learning_rate * dw
            self.bias -= self.learning_rate * db
        return self

    def predict_proba(self, X):
        X = np.asarray(X, dtype=float)
        return self.sigmoid(np.dot(X, self.weights) + self.bias)

    def predict(self, X, threshold=0.5):
        return (self.predict_proba(X) >= threshold).astype(int)

print('From-scratch Logistic Regression class created.')


# 4. Create a validation set from training data


# Make an internal 80:20 validation split using the existing training records only.
X_sub, X_val, y_sub, y_val = train_test_split(
    X_train_df, y_train, test_size=0.20, random_state=42, stratify=y_train
)

# Scale numeric columns using only the smaller training portion.
scale_columns = ['CreditScore', 'Age', 'Tenure', 'Balance', 'NumOfProducts', 'EstimatedSalary']
val_scaler = StandardScaler()
X_sub_scaled = X_sub.copy()
X_val_scaled = X_val.copy()
X_sub_scaled[scale_columns] = val_scaler.fit_transform(X_sub[scale_columns])
X_val_scaled[scale_columns] = val_scaler.transform(X_val[scale_columns])
print('Model training:', len(X_sub_scaled), '| Validation:', len(X_val_scaled))


# 5. Baseline model and hyperparameter experiments


# Compare simple configurations, like testing parameters in the college practicals.
settings = [
    (0.05, 0.0, False),
    (0.1, 0.0, False),
    (0.1, 0.01, False),
    (0.1, 0.1, False),
    (0.05, 0.0, True),
    (0.1, 0.01, True),
]
thresholds = [0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60]
results = []

for lr, regularization, balanced in settings:
    model = LogisticRegressionScratch(learning_rate=lr, epochs=1200,
                                     l2=regularization, balanced=balanced)
    model.fit(X_sub_scaled.to_numpy(), y_sub)
    probabilities = model.predict_proba(X_val_scaled.to_numpy())
    for threshold in thresholds:
        pred = (probabilities >= threshold).astype(int)
        results.append({
            'Learning Rate': lr, 'L2': regularization, 'Balanced': balanced,
            'Threshold': threshold,
            'Accuracy': accuracy_score(y_val, pred),
            'Precision': precision_score(y_val, pred, zero_division=0),
            'Recall': recall_score(y_val, pred, zero_division=0),
            'F1': f1_score(y_val, pred, zero_division=0)
        })

results_df = pd.DataFrame(results)
# Select the configuration with the best churn F1; use recall as a tie breaker.
best = results_df.sort_values(['F1', 'Recall'], ascending=False).iloc[0]
print('Top validation configurations:')
print(results_df.sort_values('F1', ascending=False).head(10).round(4).to_string(index=False))
print('\nSelected from validation:')
print(best.to_string())


# 6. Understand precision, recall and the threshold


# This graph shows the trade-off between precision and recall across thresholds.
chosen_results = results_df[
    (results_df['Learning Rate'] == best['Learning Rate']) &
    (results_df['L2'] == best['L2']) &
    (results_df['Balanced'] == best['Balanced'])
].sort_values('Threshold')
plt.figure(figsize=(8, 5))
plt.plot(chosen_results['Threshold'], chosen_results['Precision'], marker='o', label='Precision')
plt.plot(chosen_results['Threshold'], chosen_results['Recall'], marker='o', label='Recall')
plt.plot(chosen_results['Threshold'], chosen_results['F1'], marker='o', label='F1-score')
plt.xlabel('Prediction Threshold')
plt.ylabel('Score')
plt.title('Logistic Regression: threshold comparison (validation)')
plt.legend()
plt.grid(True)
plt.show()


# 7. Train the final model on all 8,000 training customers


# Apply training-only scaling, then make final predictions on unseen test customers.
final_scaler = StandardScaler()
X_train_final = X_train_df.copy()
X_test_final = X_test_df.copy()
X_train_final[scale_columns] = final_scaler.fit_transform(X_train_df[scale_columns])
X_test_final[scale_columns] = final_scaler.transform(X_test_df[scale_columns])

final_model = LogisticRegressionScratch(
    learning_rate=float(best['Learning Rate']), epochs=1200,
    l2=float(best['L2']), balanced=bool(best['Balanced'])
)
final_model.fit(X_train_final.to_numpy(), y_train)
final_prob = final_model.predict_proba(X_test_final.to_numpy())
final_pred = (final_prob >= float(best['Threshold'])).astype(int)

metrics = {
    'Accuracy': accuracy_score(y_test, final_pred),
    'Precision': precision_score(y_test, final_pred, zero_division=0),
    'Recall': recall_score(y_test, final_pred, zero_division=0),
    'F1-score': f1_score(y_test, final_pred, zero_division=0),
    'ROC-AUC': roc_auc_score(y_test, final_prob)
}
print('FINAL LOGISTIC REGRESSION RESULTS')
for name, value in metrics.items():
    print(f'{name}: {value:.4f}')
print('\nClassification Report:')
print(classification_report(y_test, final_pred, zero_division=0))
cm = confusion_matrix(y_test, final_pred)
print('Confusion Matrix:\n', cm)


# 8. Confusion matrix and ROC curve


# Confusion matrix shows correct predictions and false alarms.
fig, axes = plt.subplots(1, 2, figsize=(12, 4))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=['Stayed', 'Exited'], yticklabels=['Stayed', 'Exited'], ax=axes[0])
axes[0].set_title('Logistic Regression Confusion Matrix')
axes[0].set_xlabel('Predicted')
axes[0].set_ylabel('Actual')

# The ROC curve shows discrimination across different thresholds.
fpr, tpr, _ = roc_curve(y_test, final_prob)
axes[1].plot(fpr, tpr, label=f"ROC-AUC = {metrics['ROC-AUC']:.4f}")
axes[1].plot([0, 1], [0, 1], '--')
axes[1].set_xlabel('False Positive Rate')
axes[1].set_ylabel('True Positive Rate')
axes[1].set_title('Logistic Regression ROC Curve')
axes[1].legend()
plt.tight_layout()
plt.show()


# 9. Save results for FinSIGHT comparison and application


# Save the test metrics, validation experiments, predictions and trained model.
save_folder = output_folder / 'logistic_results'
save_folder.mkdir(parents=True, exist_ok=True)
results_df.to_csv(save_folder / 'logistic_validation_results.csv', index=False)
pd.DataFrame([metrics]).to_csv(save_folder / 'logistic_test_metrics.csv', index=False)
pd.DataFrame({'Actual': y_test, 'Predicted': final_pred,
              'Churn_Probability': final_prob}).to_csv(save_folder / 'logistic_predictions.csv', index=False)

# Store all preprocessing details so Streamlit can process a new customer correctly.
joblib.dump({'weights': final_model.weights, 'bias': final_model.bias,
             'scaler': final_scaler,
             'feature_columns': X_train_df.columns.tolist(),
             'scale_columns': scale_columns,
             'threshold': float(best['Threshold'])}, save_folder / 'logistic_model.pkl')
print('Saved outputs in:', save_folder.resolve())
print('Note: Logistic Regression predicts churn; its scores do not prove why a customer leaves.')
